"""GW5A IODELAY DLYSTEP bit order: dynamic IODELAYs with DLYSTEP = 1 << k as
input and as output delay, SDTAP and VALUE from the fabric.
usage: python3 genbits.py > bits.v"""
lines, ports, xs = [], [], []
for k in range(8):
    dyn = f".DLYSTEP(8'd{1 << k}), .SDTAP(n[0]), .VALUE(n[1])"
    ports.append(f'input i_b{k}')
    lines.append(f'    wire id_b{k}, idl_b{k};')
    lines.append(f'    IBUF ib_b{k}(.I(i_b{k}), .O(id_b{k}));')
    lines.append(f'    IODELAY #(.C_STATIC_DLY(0), .DYN_DLY_EN("TRUE")) idly_b{k}(.DI(id_b{k}), {dyn}, .DF(), .DO(idl_b{k}));')
    lines.append(f'    reg ir_b{k} = 0; always @(posedge clk) ir_b{k} <= idl_b{k};')
    xs.append(f'ir_b{k}')
    ports.append(f'output o_b{k}')
    lines.append(f'    wire od_b{k};')
    lines.append(f'    IODELAY #(.C_STATIC_DLY(0), .DYN_DLY_EN("TRUE")) odly_b{k}(.DI(n[{k + 2}]), {dyn}, .DF(), .DO(od_b{k}));')
    lines.append(f'    OBUF ob_b{k}(.I(od_b{k}), .O(o_b{k}));')
print('// generated by genbits.py')
print('module top(input clk, ' + ', '.join(ports) + ', output x);')
print('    reg [30:0] n = 0;')
print('    always @(posedge clk) n <= {n[29:0], ~(n[30] ^ n[27])};')
print('\n'.join(lines))
print(f'    assign x = {" ^ ".join(xs)};')
print('endmodule')
