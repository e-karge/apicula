"""GW5A IODELAY fuzz design: static delays as input and output delay, the
dynamic delay (DLYSTEP/SDTAP/VALUE from fabric registers), and IODELAY with
IDDR and ODDR.

usage: python3 gen.py > top.v
"""
VALUES = [0, 1, 2, 4, 8, 16, 32, 64, 128, 255]

lines, ports, xs = [], [], []
for v in VALUES:
    ports.append(f'input i_s{v}')
    lines.append(f'    wire id_s{v}, idl_s{v};')
    lines.append(f'    IBUF ib_s{v}(.I(i_s{v}), .O(id_s{v}));')
    lines.append(f'    IODELAY #(.C_STATIC_DLY({v})) idly_s{v}(.DI(id_s{v}), .DLYSTEP(8\'d0), .SDTAP(1\'b0), .VALUE(1\'b0), .DF(), .DO(idl_s{v}));')
    lines.append(f'    reg ir_s{v} = 0; always @(posedge clk) ir_s{v} <= idl_s{v};')
    xs.append(f'ir_s{v}')
    ports.append(f'output o_s{v}')
    lines.append(f'    wire od_s{v};')
    lines.append(f'    IODELAY #(.C_STATIC_DLY({v})) odly_s{v}(.DI(n[{v % 31}]), .DLYSTEP(8\'d0), .SDTAP(1\'b0), .VALUE(1\'b0), .DF(), .DO(od_s{v}));')
    lines.append(f'    OBUF ob_s{v}(.I(od_s{v}), .O(o_s{v}));')

# dynamic: DLYSTEP, SDTAP and VALUE from the LFSR
dyn = '.DLYSTEP(n[7:0]), .SDTAP(n[8]), .VALUE(n[9])'
ports.append('input i_dyn')
lines.append('    wire id_dyn, idl_dyn;')
lines.append('    IBUF ib_dyn(.I(i_dyn), .O(id_dyn));')
lines.append(f'    IODELAY #(.C_STATIC_DLY(0), .DYN_DLY_EN("TRUE")) idly_dyn(.DI(id_dyn), {dyn}, .DF(df_i), .DO(idl_dyn));')
lines.append('    reg ir_dyn = 0; always @(posedge clk) ir_dyn <= idl_dyn;')
xs += ['ir_dyn', 'df_i']
ports.append('output o_dyn')
lines.append('    wire od_dyn;')
lines.append(f'    IODELAY #(.C_STATIC_DLY(0), .DYN_DLY_EN("TRUE")) odly_dyn(.DI(n[10]), {dyn}, .DF(df_o), .DO(od_dyn));')
lines.append('    OBUF ob_dyn(.I(od_dyn), .O(o_dyn));')
xs.append('df_o')
# IODELAY + IDDR (the DQ input path) and ODDR + IODELAY (the CK path)
ports.append('input i_iddr')
lines.append('    wire id_iddr, idl_iddr, q0, q1;')
lines.append('    IBUF ib_iddr(.I(i_iddr), .O(id_iddr));')
lines.append(f'    IODELAY #(.C_STATIC_DLY(0), .DYN_DLY_EN("TRUE")) idly_iddr(.DI(id_iddr), {dyn}, .DF(), .DO(idl_iddr));')
lines.append('    IDDR iddr(.D(idl_iddr), .CLK(clk), .Q0(q0), .Q1(q1));')
xs += ['q0', 'q1']
ports.append('output o_oddr')
lines.append('    wire oq_oddr, od_oddr;')
lines.append('    ODDR oddr(.D0(n[11]), .D1(n[12]), .TX(1\'b0), .CLK(clk), .Q0(oq_oddr), .Q1());')
lines.append('    IODELAY #(.C_STATIC_DLY(37)) odly_oddr(.DI(oq_oddr), .DLYSTEP(8\'d0), .SDTAP(1\'b0), .VALUE(1\'b0), .DF(), .DO(od_oddr));')
lines.append('    OBUF ob_oddr(.I(od_oddr), .O(o_oddr));')

print('// generated by gen.py')
print('module top(input clk, ' + ', '.join(ports) + ', output x);')
print('    reg [30:0] n = 0;')
print('    always @(posedge clk) n <= {n[29:0], ~(n[30] ^ n[27])};')
print('    wire df_i, df_o;')
print('\n'.join(lines))
print(f'    assign x = {" ^ ".join(xs)};')
print('endmodule')
