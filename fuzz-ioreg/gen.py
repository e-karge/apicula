"""IO register fuzz design: every Gowin DFF type as output, input and IOBUF
(I, OEN, O) register, built from the same Verilog by the vendor and the open
toolchain.

usage: python3 gen.py [small] > top.v   (small: 10 types that cover CE,
set/reset, sync/async and the clock edge, for the small packages)
"""
import sys
# (type, has CE, set/reset port)
TYPES = [
    ('DFF', False, None), ('DFFE', True, None),
    ('DFFS', False, 'SET'), ('DFFSE', True, 'SET'), ('DFFR', False, 'RESET'), ('DFFRE', True, 'RESET'),
    ('DFFP', False, 'PRESET'), ('DFFPE', True, 'PRESET'), ('DFFC', False, 'CLEAR'), ('DFFCE', True, 'CLEAR'),
]
TYPES += [(t.replace('DFF', 'DFFN'), ce, sr) for t, ce, sr in TYPES]
ALL_TYPES = TYPES
if 'small' in sys.argv:
    TYPES = [t for t in TYPES if t[0] in {'DFF', 'DFFE', 'DFFS', 'DFFRE', 'DFFP', 'DFFCE',
                                          'DFFN', 'DFFNSE', 'DFFNR', 'DFFNPE'}]
# IOBUF variants: all three registers of one type
IOBUF_TYPES = ['DFF', 'DFFRE', 'DFFNPE']

def ff(name, typ, d, q, init=None):
    ce, sr = next((c, s) for t, c, s in ALL_TYPES if t == typ)
    ports = [f'.D({d})', f'.Q({q})', '.CLK(clk)']
    if ce:
        ports.append('.CE(ce)')
    if sr:
        ports.append(f'.{sr}(rst)')
    return f'    {typ} {name}({", ".join(ports)});'

lines = []
outs, ins, ios = [], [], []
for i, (t, _, _) in enumerate(TYPES):
    outs.append(f'o_{t.lower()}')
    lines.append(f'    wire oq_{i};')
    lines.append(ff(f'or_{i}', t, f'n[{i}]', f'oq_{i}'))
    lines.append(f'    OBUF ob_{i}(.I(oq_{i}), .O(o_{t.lower()}));')
for i, (t, _, _) in enumerate(TYPES):
    ins.append(f'i_{t.lower()}')
    lines.append(f'    wire id_{i}, iq_{i};')
    lines.append(f'    IBUF ib_{i}(.I(i_{t.lower()}), .O(id_{i}));')
    lines.append(ff(f'ir_{i}', t, f'id_{i}', f'iq_{i}'))
for i, t in enumerate(IOBUF_TYPES):
    ios.append(f'b_{t.lower()}')
    lines.append(f'    wire bo_{i}, bt_{i}, bi_{i}, bq_{i};')
    lines.append(ff(f'bor_{i}', t, f'n[{i + 3}]', f'bo_{i}'))
    lines.append(ff(f'btr_{i}', t, f'n[{i + 7}]', f'bt_{i}'))
    lines.append(f'    IOBUF bb_{i}(.I(bo_{i}), .OEN(bt_{i}), .O(bi_{i}), .IO(b_{t.lower()}));')
    lines.append(ff(f'bir_{i}', t, f'bi_{i}', f'bq_{i}'))

# IOBUFs with only some registers: OEN, O, and output registers of the two
# types nextpnr combines (DFFS/DFFR); the others are driven from LUTs
part = [('b_oen', 'DFF', ('t',)), ('b_out', 'DFF', ('o',)), ('b_sr', 'DFFS', ('o', 'tr'))]
for j, (name, t, regs) in enumerate(part):
    i = len(IOBUF_TYPES) + j
    ios.append(name)
    lines.append(f'    wire bo_{i}, bt_{i}, bi_{i};')
    lines.append(ff(f'bor_{i}', t, f'n[{i + 3}]', f'bo_{i}') if 'o' in regs else f'    assign bo_{i} = n[{i + 3}] ^ n[{i + 11}];')
    if 'tr' in regs:
        lines.append(ff(f'btr_{i}', 'DFFR', f'n[{i + 7}]', f'bt_{i}'))
    elif 't' in regs:
        lines.append(ff(f'btr_{i}', t, f'n[{i + 7}]', f'bt_{i}'))
    else:
        lines.append(f'    assign bt_{i} = n[{i + 7}] ^ n[{i + 13}];')
    lines.append(f'    IOBUF bb_{i}(.I(bo_{i}), .OEN(bt_{i}), .O(bi_{i}), .IO({name}));')
    lines.append(f'    wire bq_{i} = bi_{i};')

print('// generated by gen.py')
print('module top(input clk, input ce, input rst,')
print('    output ' + ', output '.join(outs) + ',')
print('    input ' + ', input '.join(ins) + ',')
print('    inout ' + ', inout '.join(ios) + ',')
print('    output x);')
print('    reg [31:0] n = 0;')
print('    always @(posedge clk) n <= {n[30:0], ~(n[31] ^ n[21] ^ n[1] ^ n[0])};')
print('\n'.join(lines))
xs = [f'iq_{i}' for i in range(len(TYPES))] + [f'bq_{i}' for i in range(len(IOBUF_TYPES) + len(part))]
print(f'    assign x = {" ^ ".join(xs)};')
print('endmodule')
